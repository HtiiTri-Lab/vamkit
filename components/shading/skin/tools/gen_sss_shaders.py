"""shaders\\sss.hlsl -> <repo>\\out\\gen\\skin\\sss_shaders.h (the subsurface passes' bytecode, native\\sss.cpp).

    python -I gen_sss_shaders.py   (VAMKIT_FXC)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import skin_shaders as S  # noqa: E402

ENTRIES = [("SssPrep", "cs_5_0"), ("SssBlur", "cs_5_0"), ("SssVS", "vs_5_0"), ("SssComp", "ps_5_0")]


def main():
    root = os.path.dirname(HERE)
    src = open(os.path.join(root, "shaders", "sss.hlsl"), encoding="utf-8").read()
    out = os.path.join(S.gen_dir(), "sss_shaders.h")
    with open(out, "w") as f:
        f.write("// generated by tools\\gen_sss_shaders.py from shaders\\sss.hlsl\n#pragma once\n")
        for entry, target in ENTRIES:
            code = S.compile_hlsl(src, entry, target, name="sss.hlsl")
            f.write("static const unsigned char k%s[%d] = {%s};\n" % (entry, len(code), ",".join(str(b) for b in code)))
    print("%d shaders -> %s" % (len(ENTRIES), out))


if __name__ == "__main__":
    main()
