"""Compile shaders/hair_onepass.hlsl with fxc into <repo>/out/gen/hair-strands/hop_shaders.h: the vertex and hull shader, the domain shader
per light count (0..8), the geometry and pixel shader per light count and screen interpolant (HOP_SCREEN 0 / 1); and
the same for the lights-only draw (HOP_BASE 0, 1..8 lights: kHopL*). Assembly listings go to <repo>/out/hair-strands/shaders.

usage: set VAMKIT_FXC, then python -I build_onepass_shaders.py
"""
import concurrent.futures
import os
import subprocess
import sys
from pathlib import Path

REPO = next(p for p in Path(__file__).resolve().parents if (p / "components").is_dir())
COMP = Path(__file__).resolve().parent.parent
GEN = REPO / "out" / "gen" / "hair-strands"
OUT = REPO / "out" / "hair-strands"


def find_fxc():
    v = os.environ.get("VAMKIT_FXC")
    if not v:
        raise SystemExit("set VAMKIT_FXC to the Windows SDK bin folder for x64 (the one holding fxc.exe)")
    f = v if v.lower().endswith(".exe") else os.path.join(v, "fxc.exe")
    if not os.path.isfile(f):
        raise SystemExit("VAMKIT_FXC=%s: no fxc.exe there" % v)
    return f

MAX_LIGHTS = 8


def main():
    src = str(COMP / "shaders" / "hair_onepass.hlsl")
    out_dir = str(OUT / "shaders")
    os.makedirs(out_dir, exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)
    fxc = find_fxc()
    jobs = [("HopVS", "vs_5_0", None, None, 1), ("HopHS", "hs_5_0", None, None, 1)]
    for base, first in ((1, 0), (0, 1)):
        jobs += [("HopDS", "ds_5_0", n, None, base) for n in range(first, MAX_LIGHTS + 1)]
        jobs += [(e, t, n, s, base) for e, t in (("HopGS", "gs_5_0"), ("HopPS", "ps_5_0")) for n in range(first, MAX_LIGHTS + 1) for s in (0, 1)]

    def compile_one(job):
        entry, target, n, s, base = job
        name = entry + ("" if base else "L") + ("" if n is None else "_%d" % n) + ("" if s is None else "_%d" % s)
        cmd = [fxc, "/nologo", "/O3", "/T", target, "/E", entry, "/Fo", os.path.join(out_dir, name + ".cso"),
               "/Fc", os.path.join(out_dir, name + ".asm")]
        if n is not None:
            cmd += ["/D", "HOP_LIGHTS=%d" % n]
        if s is not None:
            cmd += ["/D", "HOP_SCREEN=%d" % s]
        cmd += ["/D", "HOP_BASE=%d" % base]
        r = subprocess.run(cmd + [src], capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit("fxc %s failed:\n%s%s" % (name, r.stdout, r.stderr))
        return name, open(os.path.join(out_dir, name + ".cso"), "rb").read()

    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        results = dict(pool.map(compile_one, jobs))

    lines = ["// Generated by tools/build_onepass_shaders.py from shaders/hair_onepass.hlsl. Do not edit.", "#pragma once",
             "#include <stddef.h>", "#include <stdint.h>", "", "#define HOP_SHADER_MAX_LIGHTS %d" % MAX_LIGHTS, ""]
    for name, code in results.items():
        body = ",".join("0x%02x" % b for b in code)
        lines.append("static const uint8_t kHop_%s[%d] = {%s};" % (name, len(code), body))
    lines += ["", "struct HopBytecode { const uint8_t *code; size_t size; };",
              "static const HopBytecode kHopVS = {kHop_HopVS, sizeof kHop_HopVS};",
              "static const HopBytecode kHopHS = {kHop_HopHS, sizeof kHop_HopHS};",
              "static const HopBytecode kHopDS[%d] = {%s};" % (MAX_LIGHTS + 1, ", ".join(
                  "{kHop_HopDS_%d, sizeof kHop_HopDS_%d}" % (n, n) for n in range(MAX_LIGHTS + 1)))]
    for e in ("GS", "PS"):
        lines.append("static const HopBytecode kHop%s[%d][2] = {%s};" % (e, MAX_LIGHTS + 1, ", ".join(
            "{{kHop_Hop%s_%d_0, sizeof kHop_Hop%s_%d_0}, {kHop_Hop%s_%d_1, sizeof kHop_Hop%s_%d_1}}" % (e, n, e, n, e, n, e, n)
            for n in range(MAX_LIGHTS + 1))))
    # lights only: none for 0 lights
    lines.append("static const HopBytecode kHopLDS[%d] = {{NULL, 0}, %s};" % (MAX_LIGHTS + 1, ", ".join(
        "{kHop_HopDSL_%d, sizeof kHop_HopDSL_%d}" % (n, n) for n in range(1, MAX_LIGHTS + 1))))
    for e in ("GS", "PS"):
        lines.append("static const HopBytecode kHopL%s[%d][2] = {{{NULL, 0}, {NULL, 0}}, %s};" % (e, MAX_LIGHTS + 1, ", ".join(
            "{{kHop_Hop%sL_%d_0, sizeof kHop_Hop%sL_%d_0}, {kHop_Hop%sL_%d_1, sizeof kHop_Hop%sL_%d_1}}" % (e, n, e, n, e, n, e, n)
            for n in range(1, MAX_LIGHTS + 1))))
    path = str(GEN / "hop_shaders.h")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("%d shaders (%d KB) -> %s" % (len(results), sum(len(c) for c in results.values()) // 1024, path))


if __name__ == "__main__":
    main()
