"""Generate <repo>/out/gen/hair-strands/hair_programs.h: every program of GPUTools/MeshedVR/HairOpt, read straight from
VaM (VaM_Data/resources.assets, through components/shading/skin/tools/skin_shaders.py), keyed by the first 8 bytes of
the SHA-1 of its bytecode, with its pass, stage, keywords, constant buffer layouts and texture / buffer slots. The
native side tags each shader object the game creates from one of these programs.

usage: set VAMKIT_VAM=<VaM folder> and VAMKIT_FXC (see skin_shaders.py), then: python -I gen_programs.py
"""
import collections
import hashlib
import os
import sys
from pathlib import Path

REPO = next(p for p in Path(__file__).resolve().parents if (p / "components").is_dir())
sys.path.insert(0, str(REPO / "components" / "shading" / "skin" / "tools"))
import skin_shaders as S  # noqa: E402

STAGES = {"progVertex": 0, "progHull": 1, "progDomain": 2, "progGeometry": 3, "progFragment": 4}
STAGE_FILE = {0: "vs", 1: "hs", 2: "ds", 3: "gs", 4: "ps"}
PASSES = {"FORWARDBASE": 0, "FORWARDADD": 1, "SHADOWCASTER": 2, "": 3}  # 3 = MOTIONVECTORS (unnamed pass)
KEYWORDS = ["DIRECTIONAL", "DIRECTIONAL_COOKIE", "POINT", "POINT_COOKIE", "SPOT", "SHADOWS_SCREEN", "SHADOWS_DEPTH",
            "SHADOWS_CUBE", "SHADOWS_SOFT", "LIGHTPROBE_SH", "VERTEXLIGHT_ON", "UNITY_SINGLE_PASS_STEREO",
            "STEREO_CUBEMAP_RENDER_ON"]
# keywords that never change which light a pixel shader draws (shared bytecode may differ only in these)
LOOSE = {"LIGHTPROBE_SH", "VERTEXLIGHT_ON", "UNITY_SINGLE_PASS_STEREO", "STEREO_CUBEMAP_RENDER_ON"}
TYPE_BYTES = {"vec1": 4, "vec2": 8, "vec3": 12, "vec4": 16, "mat4": 64, "mat3": 48}


def kw_bits(kws):
    b = 0
    for k in kws:
        if k not in KEYWORDS:
            raise SystemExit("unknown keyword " + k)
        b |= 1 << KEYWORDS.index(k)
    return b


def main():
    with open(os.path.join(S.vam_root(), "VaM_Data", "resources.assets"), "rb") as f:
        data = f.read()
    found = S.load(r"^GPUTools/MeshedVR/HairOpt$", data)
    if len(found) != 1:
        raise SystemExit("expected one GPUTools/MeshedVR/HairOpt shader in resources.assets, found %d" % len(found))
    _name, summary, blobs, _pid = found[0]
    progs = collections.OrderedDict()  # hash64 -> entry
    for p in summary["subshaders"][0]["passes"]:
        pas = PASSES[p["name"]]
        for st, subs in p["stages"].items():
            stage = STAGES[st]
            for sp in subs:
                code = blobs[sp["blob"]]
                h = hashlib.sha1(code).digest()
                h64 = int.from_bytes(h[:8], "big")
                kws = sp["keywords"]
                strict = kw_bits([k for k in kws if k not in LOOSE])
                e = progs.get(h64)
                if e is None:
                    e = progs[h64] = {"hash": h64, "hex": h.hex()[:10], "stage": stage, "passes": set(), "strict": set(),
                                      "kw": kw_bits(kws), "sp": sp, "size": len(code)}
                e["passes"].add(pas)
                e["strict"].add(strict)
    # lit pixel shaders must say which pass and which light they draw (shadow casters may be shared)
    for e in progs.values():
        if e["stage"] == 4 and (len(e["passes"]) != 1 or (e["passes"] & {0, 1} and len(e["strict"]) != 1)):
            raise SystemExit("pixel shader %s is shared across passes or lights: %s %s" % (e["hex"], e["passes"], e["strict"]))

    out = ["// Generated by tools/gen_programs.py from GPUTools/MeshedVR/HairOpt (VaM resources.assets). Do not edit.",
           "#pragma once", "#include <stdint.h>", ""]
    for i, k in enumerate(KEYWORDS):
        out.append("#define HOP_KW_%s (1u << %d)" % (k, i))
    out += ["", "enum { HOP_PASS_FB = 0, HOP_PASS_FA = 1, HOP_PASS_SC = 2, HOP_PASS_MV = 3, HOP_PASS_SHARED = 15 };",
            "enum { HOP_VS = 0, HOP_HS = 1, HOP_DS = 2, HOP_GS = 3, HOP_PS = 4 };", "",
            "struct HopMember { const char *name; uint16_t offset, bytes; };",
            "struct HopCb { const char *name; uint16_t size; uint8_t slot, count; const HopMember *members; };",
            "struct HopRes { const char *name; uint8_t slot, sampler, dim; };  // dim: 2 = 2D, 4 = cube; buffers dim 0",
            "struct HopProgram {",
            "    uint64_t hash;      // first 8 bytes of SHA-1(bytecode), big-endian",
            "    const char *hex;    // first 10 hex digits (data/asm file name)",
            "    uint32_t size;      // bytecode bytes",
            "    uint8_t stage, pass;",
            "    uint32_t keywords;  // HOP_KW_* of the first variant using it",
            "    uint8_t cbCount, texCount, bufCount;",
            "    const HopCb *cbs;",
            "    const HopRes *tex;",
            "    const HopRes *buf;",
            "};", ""]
    entries = []
    for n, e in enumerate(progs.values()):
        sp = e["sp"]
        slots = dict(sp["cbBind"])
        cbnames = []
        for ci, cb in enumerate(sp["cbuffers"]):
            mem = "kMem%d_%d" % (n, ci)
            members = [(k,) + tuple(v) for k, v in cb["members"].items()]
            members.sort(key=lambda m: m[1])  # name, offset, array size, type; by offset
            out.append("static const HopMember %s[] = {%s};" % (mem, ", ".join(
                '{"%s", %d, %d}' % (m[0], m[1], TYPE_BYTES[m[3]] * max(1, m[2])) for m in members) or "{0, 0, 0}"))
            cbnames.append('{"%s", %d, %d, %d, %s}' % (cb["name"], cb["size"], slots[cb["name"]], len(members), mem))
        cbs = "kCb%d" % n
        out.append("static const HopCb %s[] = {%s};" % (cbs, ", ".join(cbnames) or '{0, 0, 0, 0, 0}'))
        tex = "kTex%d" % n
        out.append("static const HopRes %s[] = {%s};" % (tex, ", ".join(
            '{"%s", %d, %d, %d}' % (t[0], t[1], t[2], t[3]) for t in ((k,) + tuple(v) for k, v in sp["textures"].items())) or "{0, 0, 0, 0}"))
        buf = "kBuf%d" % n
        out.append("static const HopRes %s[] = {%s};" % (buf, ", ".join(
            '{"%s", %d, 0, 0}' % (b[0], b[1]) for b in sp["buffers"].items()) or "{0, 0, 0, 0}"))
        pas = next(iter(e["passes"])) if len(e["passes"]) == 1 else 15
        entries.append('    {0x%016xull, "%s", %d, %d, %d, 0x%x, %d, %d, %d, %s, %s, %s},' % (
            e["hash"], e["hex"], e["size"], e["stage"], pas, e["kw"], len(sp["cbuffers"]), len(sp["textures"]),
            len(sp["buffers"]), cbs, tex, buf))
    out += ["", "static const HopProgram kHopPrograms[] = {"] + entries + ["};",
            "static const int kHopProgramCount = %d;" % len(entries), ""]
    gen = REPO / "out" / "gen" / "hair-strands"
    gen.mkdir(parents=True, exist_ok=True)
    path = str(gen / "hair_programs.h")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    by = collections.Counter((STAGE_FILE[e["stage"]]) for e in progs.values())
    print("%d programs (%s) -> %s" % (len(progs), ", ".join("%s %d" % kv for kv in sorted(by.items())), path))


if __name__ == "__main__":
    main()
