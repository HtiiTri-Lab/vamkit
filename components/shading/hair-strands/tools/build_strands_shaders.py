"""Compile shaders/hair_strands.hlsl (and shaders/hs_domain.hlsl) with fxc into <repo>/out/gen/hair-strands/hs_shaders.h: the build, raster
(depth pass, id pass) and resolve (vertex shader, ForwardBase and ForwardAdd pixel shaders) programs, and the isoline
domain read-back shaders. Assembly listings go to <repo>/out/hair-strands/shaders.

usage: set VAMKIT_FXC, then python -I build_strands_shaders.py
"""
import concurrent.futures
import os
import subprocess
import sys
from pathlib import Path

REPO = next(p for p in Path(__file__).resolve().parents if (p / "components").is_dir())
COMP = Path(__file__).resolve().parent.parent
GEN = REPO / "out" / "gen" / "hair-strands"
OUT = REPO / "out" / "hair-strands"


def find_fxc():
    v = os.environ.get("VAMKIT_FXC")
    if not v:
        raise SystemExit("set VAMKIT_FXC to the Windows SDK bin folder for x64 (the one holding fxc.exe)")
    f = v if v.lower().endswith(".exe") else os.path.join(v, "fxc.exe")
    if not os.path.isfile(f):
        raise SystemExit("VAMKIT_FXC=%s: no fxc.exe there" % v)
    return f


# name, source, entry, target, defines
JOBS = [
    ("Build", "hair_strands.hlsl", "HsBuild", "cs_5_0", {"HS_BUILD": 1}),
    ("RasterDepth", "hair_strands.hlsl", "HsRaster", "cs_5_0", {"HS_RASTER": 1, "HS_PASS_ID": 0}),
    ("RasterId", "hair_strands.hlsl", "HsRaster", "cs_5_0", {"HS_RASTER": 1, "HS_PASS_ID": 1}),
    ("ClipDepth", "hair_strands.hlsl", "HsRasterGroup", "cs_5_0", {"HS_RASTER": 1, "HS_PASS_ID": 0, "HS_CLIPPED": 1}),
    ("ClipId", "hair_strands.hlsl", "HsRasterGroup", "cs_5_0", {"HS_RASTER": 1, "HS_PASS_ID": 1, "HS_CLIPPED": 1}),
    ("ResolveVS", "hair_strands.hlsl", "HsResolveVS", "vs_5_0", {"HS_RESOLVE": 1}),
    ("ResolveFb", "hair_strands.hlsl", "HsResolvePS", "ps_5_0", {"HS_RESOLVE": 1, "HS_FORWARD_ADD": 0}),
    ("ResolveFa", "hair_strands.hlsl", "HsResolvePS", "ps_5_0", {"HS_RESOLVE": 1, "HS_FORWARD_ADD": 1}),
    ("ClipResolveFb", "hair_strands.hlsl", "HsResolvePS", "ps_5_0", {"HS_RESOLVE": 1, "HS_FORWARD_ADD": 0, "HS_CLIPPED": 1}),
    ("ClipResolveFa", "hair_strands.hlsl", "HsResolvePS", "ps_5_0", {"HS_RESOLVE": 1, "HS_FORWARD_ADD": 1, "HS_CLIPPED": 1}),
    ("DomainVS", "hs_domain.hlsl", "VS", "vs_5_0", {}),
    ("DomainHS", "hs_domain.hlsl", "HS", "hs_5_0", {}),
    ("DomainDS", "hs_domain.hlsl", "DS", "ds_5_0", {}),
]


def main():
    out_dir = str(OUT / "shaders")
    os.makedirs(out_dir, exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)
    fxc = find_fxc()

    def compile_one(job):
        name, src, entry, target, defines = job
        cmd = [fxc, "/nologo", "/O3", "/T", target, "/E", entry, "/Fo", os.path.join(out_dir, name + ".cso"),
               "/Fc", os.path.join(out_dir, name + ".asm")]
        for k, v in defines.items():
            cmd += ["/D", "%s=%d" % (k, v)]
        r = subprocess.run(cmd + [str(COMP / "shaders" / src)], capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit("fxc %s failed:\n%s%s" % (name, r.stdout, r.stderr))
        return name, open(os.path.join(out_dir, name + ".cso"), "rb").read()

    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        results = dict(pool.map(compile_one, JOBS))

    lines = ["// Generated by tools/build_strands_shaders.py from shaders/hair_strands.hlsl and shaders/hs_domain.hlsl. Do not edit.",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    for name, _, _, _, _ in JOBS:
        code = results[name]
        lines.append("static const uint8_t kHs_%s[%d] = {%s};" % (name, len(code), ",".join("0x%02x" % b for b in code)))
    lines += ["", "struct HsBytecode { const uint8_t *code; size_t size; };"]
    for name, _, _, _, _ in JOBS:
        lines.append("static const HsBytecode kHs%s = {kHs_%s, sizeof kHs_%s};" % (name, name, name))
    with open(GEN / "hs_shaders.h", "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("hs_shaders.h: %s" % ", ".join("%s %d B" % (n, len(results[n])) for n, _, _, _, _ in JOBS))


if __name__ == "__main__":
    main()
