"""Unity's shadow map for VaM's Custom/Subsurface shaders, through their fallbacks: which ShadowCaster draws a material
of the shader and what it keeps. Writes <repo>/out/gen/skin/PathShadowCasters.cs (RtScene's solid shadow, 0.23.7; the
checked-in components/shading/skin/PathShadowCasters.cs is a copy of that).

    python -I shadow_casters.py [--print]   (VAMKIT_VAM, VAMKIT_FXC)

VaM's translucent clothing shaders have no ShadowCaster of their own; Unity takes the first one along the fallback
chain. Three forms are recognised from the program itself (docs/sheer-cloth-20261105):
  1 separate alpha: discard where saturate(_AlphaTex.a + _AlphaAdjust) < _Cutoff (TransparentCutoutSeparateAlpha...)
  2 main alpha:     discard where saturate(_MainTex.a) * _Color.a < _Cutoff (Cutout, CutoutNoCull...)
  3 solid:          no discard at all (NoCull...)
Anything else (no caster, another program) is left out: the tracers keep their own rule for it.
"""
import os, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from shader_sources import serialized_sources, S, GEN

OUT = GEN / 'PathShadowCasters.cs'


def code_lines(asm):
    return [l.strip() for l in asm.splitlines() if l.strip() and not l.lstrip().startswith(('//', 'dcl_', 'ps_'))]


def member(program, name):
    g = [c for c in program['cbuffers'] if c['name'] == '$Globals']
    if not g or name not in g[0]['members']: return None
    off = g[0]['members'][name][0]
    return 'cb0[%d].%s' % (off // 16, 'xyzw'[(off % 16) // 4])


def classify(program, asm):
    lines = code_lines(asm)
    if not any(l.startswith('discard') for l in lines):
        return 3 if not program['textures'] else 0
    textures = sorted(program['textures'])
    cutoff, adjust, color = member(program, '_Cutoff'), member(program, '_AlphaAdjust'), member(program, '_Color')
    if cutoff is None: return 0
    body = ' ; '.join(lines)
    tail = r' ; lt (?P=t)\.x, (?P=t)\.x, l\(0\.000000\) ; discard_nz (?P=t)\.x ; mov o0\.xyzw, l\(0,0,0,0\) ; ret$'
    if textures == ['_AlphaTex'] and adjust:
        for a in (r'sample\S* (?P<s>r\d)\.xyzw, v1\.xyxx, t0\.xyzw, s0 ; add_sat (?P<t>r\d)\.x, (?P=s)\.w, ',
                  r'sample\S* (?P<s>r\d)\.x, v1\.xyxx, t0\.wxyz, s0 ; add_sat (?P<t>r\d)\.x, (?P=s)\.x, '):
            if re.search('^' + a + re.escape(adjust) + r' ; add (?P=t)\.x, (?P=t)\.x, -' + re.escape(cutoff) + tail, body):
                return 1
    if textures == ['_MainTex'] and color:
        reg = color.split('.')[0] + '.w'  # _Color.a
        if re.search(r'^sample\S* (?P<t>r\d)\.(?:x|xyzw), v1\.xyxx, t0\.wxyz, s0 ; mov_sat (?P=t)\.x, (?P=t)\.x ; mad (?P=t)\.x, (?P=t)\.x, '
                     + re.escape(reg) + r', -' + re.escape(cutoff) + tail, body):
            return 2
    return 0


def main():
    nodes = S.P.load_type_tree()
    fallback, caster = {}, {}
    for source, data in serialized_sources():
        endian, types, objects = S.B.read_serialized(data)
        for pid, start, size, kind in objects:
            if types[kind][0] != 48: continue
            name = S.shader_name(data[start:start + size])
            if not name or name in fallback: continue
            tree = types[kind][1]
            try: value, _ = S.P.parse(tree.nodes if tree else nodes, data, start, endian)
            except Exception: continue
            fallback[name] = value['m_ParsedForm'].get('m_FallbackName', '') or ''
    for source, data in serialized_sources():
        for name, summary, blobs, pid in S.load(r'.*', data):
            if name in caster: continue
            caster[name] = None
            for ps in summary['subshaders'][0]['passes'] if summary['subshaders'] else []:
                if ps['tags'].get('LIGHTMODE', '').upper() != 'SHADOWCASTER': continue
                programs = ps['stages']['progFragment']
                forms = {classify(p, S.disassemble(blobs[p['blob']])) for p in programs}
                caster[name] = forms.pop() if len(forms) == 1 else 0  # every variant the same form, or none of them
                break

    def resolve(name, depth=0):
        if caster.get(name) is not None: return caster[name], name
        nxt = fallback.get(name, '')
        if not nxt or depth > 8: return 0, ''
        return resolve(nxt, depth + 1)

    rows = []
    for name in sorted(set(fallback) | set(caster)):
        if not name.startswith('Custom/Subsurface/'): continue
        form, via = resolve(name)
        if form: rows.append((name, form, via))
    if '--print' in sys.argv:
        for r in rows: print('%d %s  <- %s' % (r[1], r[0], r[2]))
    text = ['// Generated by tools/path_tracing/shadow_casters.py from the installed shaders (docs/sheer-cloth-20261105).',
            '// Unity\'s shadow map for a Custom/Subsurface material: the first ShadowCaster along the shader\'s fallbacks.',
            '//   1 discards where saturate(_AlphaTex.a + _AlphaAdjust) < _Cutoff, 2 where saturate(_MainTex.a) x _Color.a < _Cutoff,',
            '//   3 draws every pixel; 0 (not listed): no caster the tracers can follow.',
            'internal static class PathShadowCasters {',
            '  internal const int None=0,SeparateAlpha=1,MainAlpha=2,Solid=3;',
            '  internal static int Of(string shader) { switch(shader) {']
    for name, form, via in rows:
        text.append('    case "%s": return %d; // %s' % (name, form, via))
    text += ['    default: return None; } }', '}', '']
    OUT.write_text('\n'.join(text), encoding='utf-8')
    print('%d shaders -> %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
