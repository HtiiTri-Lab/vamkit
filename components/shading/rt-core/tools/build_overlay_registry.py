"""Stock UI pixel-program identities, read from installed engine assets.
-> <repo>/out/gen/skin: path_overlay_programs.h, overlay-programs.json. python -I build_overlay_registry.py (VAMKIT_VAM)"""
import hashlib,json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
from shader_sources import serialized_sources,S,GEN
keys={};environment={};effects={};discard={}
for source,data in serialized_sources():
    for name,summary,blobs,pid in S.load(r'^(UI/|GUI/|Hidden/Internal-GUI|Custom/SteamVR_|Custom/Discard$|Custom/Subsurface/OverlayEmissive|Custom/Transparent(HUD|Billboard)$|Battlehub/RT(Gizmos|Handles)/|Battlehub/RTCommon/Billboard$|MK/Glow/Selective/UI/|Particles/|Mobile/Particles/|Hidden/Internal-(Flare|Halo)$|Skybox/|Marmoset/Skybox IBL$)',data):
        for sub in summary['subshaders']:
            for ps in sub['passes']:
                for p in ps['stages']['progFragment']:
                    code=blobs[p['blob']]
                    if code:
                        target=discard if name=='Custom/Discard' else environment if name.startswith(('Skybox/','Marmoset/Skybox IBL')) else effects if name.startswith(('Particles/','Mobile/Particles/','Hidden/Internal-Flare','Hidden/Internal-Halo')) else keys
                        target[int.from_bytes(hashlib.sha1(code).digest()[:8],'big')]=name
target=GEN/'path_overlay_programs.h'
target.write_text('// Generated by build_overlay_registry.py from stock pixel programs.\n'+''.join('static const uint64_t '+name+'[]={\n'+''.join('0x%016xull,\n'%key for key in sorted(table))+'};\n' for name,table in [('kPathOverlayPrograms',keys),('kPathEffectPrograms',effects),('kPathEnvironmentPrograms',environment),('kPathDiscardPrograms',discard)]),encoding='utf-8')
(GEN/'overlay-programs.json').write_text(json.dumps({format(k,'016x'):v for k,v in sorted(keys.items())},indent=2),encoding='utf-8')
print('overlay pixel programs:',len(keys))
print('environment pixel programs:',len(environment))
print('effect pixel programs:',len(effects))
print('unconditional discard pixel programs:',len(discard))
