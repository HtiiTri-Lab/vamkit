"""<repo>\\out\\gen\\rt-core\\rtc_shaders.h: one DXIL blob (root signature inside) per RtCore pass - the scene passes
(shaders\\path_scene.hlsl) and the path tracer's (shaders\\path_*.hlsl), in rtcore.cpp's Pipe order.
Windows SDK dxc + dxil.dll (signed): VAMKIT_DXC, the SDK's bin\\<version>\\x64 directory (or dxc.exe itself).

The passes compile side by side (VAMKIT_JOBS processes, default half the logical processors, at most 8). Nothing is
compiled when the header is there and nothing it is made from has changed: the shaders, the headers they include, this
script and the compiler (a hash of all of them is kept beside the header, rtc_shaders.inputs).

    python -I tools\\gen_shaders.py [--force]
"""
import hashlib
import os
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

root = Path(__file__).resolve().parents[1]
repo = root.parents[2]


def dxc():
    v = os.environ.get('VAMKIT_DXC')
    if not v:
        sys.exit('set VAMKIT_DXC to the Windows SDK bin\\<version>\\x64 directory (or dxc.exe)')
    p = Path(v)
    return p / 'dxc.exe' if p.is_dir() else p


DXC = dxc()
NVAPI = repo / 'third_party' / 'nvapi'
ENTRIES = ['ClearBuffer', 'Tessellate', 'PathTrace', 'PathHairPrepare', 'PathSkin',
           'PathEnvironmentCdf', 'PathEmitterCdf', 'PathEmitterRanges', 'PathTraceRaygen', 'PathTraceSplit', 'PathTraceSplitRaygen',
           'PathOmmBake', 'PathTraceSss', 'PathTraceSssRaygen', 'PathScatterX', 'PathScatterY']
SOURCES = {'ClearBuffer': 'path_scene.hlsl', 'Tessellate': 'path_scene.hlsl', 'PathHairPrepare': 'path_hair.hlsl',
           'PathSkin': 'path_skinning.hlsl', 'PathOmmBake': 'path_omm.hlsl',
           'PathScatterX': 'path_scatter.hlsl', 'PathScatterY': 'path_scatter.hlsl'}


def inputs():
    """A hash of everything the header is made from."""
    h = hashlib.sha256()
    files = [Path(__file__).resolve()]
    files += sorted(p for folder in (root / 'shaders', root / 'third_party') for p in folder.rglob('*') if p.is_file())
    files += sorted(p for p in NVAPI.glob('*') if p.suffix.lower() in ('.h', '.hlsl', '.hlsli'))
    for p in files:
        h.update(p.name.encode())
        h.update(p.read_bytes())
    for tool in (DXC, DXC.with_name('dxil.dll')):
        if tool.is_file():
            s = tool.stat()
            h.update(('%s %d %d' % (tool.name, s.st_size, s.st_mtime_ns)).encode())
    return h.hexdigest()


def compile_entry(e, tmp):
    out = Path(tmp) / (e + '.cso')
    entry = e.replace('Split', '').replace('Sss', '')
    stage = ['-T', 'lib_6_5', '-exports', entry, '-D', 'PT_RAYGEN=1'] if e.endswith('Raygen') else ['-T', 'cs_6_5', '-E', entry]
    if 'Split' in e:
        stage += ['-D', 'PT_SPLIT=1']
    if 'Sss' in e:
        stage += ['-D', 'PT_SSS=1']  # the skin's scattering in screen space (docs/knowledge/skin.md)
    r = subprocess.run([str(DXC), '-nologo', *stage, '-HV', '2021', '-O3', '-WX', '-I', str(NVAPI),
                        '-Fo', str(out), str(root / 'shaders' / SOURCES.get(e, 'path_trace.hlsl'))], capture_output=True, text=True)
    if r.returncode != 0:
        return '%s:\n%s%s\n' % (e, r.stdout, r.stderr)
    return out.read_bytes()


gen = repo / 'out' / 'gen' / 'rt-core'
header, stamp = gen / 'rtc_shaders.h', gen / 'rtc_shaders.inputs'
state = inputs()
if '--force' not in sys.argv[1:] and header.is_file() and stamp.is_file() and stamp.read_text() == state:
    print('rtc_shaders.h is up to date')
    sys.exit(0)

jobs = int(os.environ.get('VAMKIT_JOBS') or max(1, min(8, (os.cpu_count() or 2) // 2)))
with tempfile.TemporaryDirectory() as tmp, ThreadPoolExecutor(max_workers=jobs) as pool:
    results = list(pool.map(lambda e: compile_entry(e, tmp), ENTRIES))
errors = [r for r in results if isinstance(r, str)]
if errors:
    sys.stderr.write(''.join(errors))
    sys.exit(1)
blobs = dict(zip(ENTRIES, results))

gen.mkdir(parents=True, exist_ok=True)
with header.open('w') as f:
    f.write('#pragma once\n// generated by components\\shading\\rt-core\\tools\\gen_shaders.py (DXIL, root signature inside)\n')
    f.write('#include <stddef.h>\nnamespace rtc_shaders {\n')
    for e, code in blobs.items():
        f.write('static const unsigned char k%s[] = {%s};\n' % (e, ','.join(str(b) for b in code)))
    f.write('struct Blob { const char *name; const unsigned char *code; size_t size; };\n')
    f.write('static const Blob kAll[] = {\n')
    for e in blobs:
        f.write('    {"%s", k%s, sizeof k%s},\n' % (e, e, e))
    f.write('};\n}  // namespace rtc_shaders\n')
stamp.write_text(state)
for e, code in blobs.items():
    print('%-13s %6d bytes' % (e, len(code)))
