"""Compile shaders/tonemap.hlsl's compute programs with fxc (cs_5_0, /O3) into <repo>/out/gen/tone-mapping/tm_shaders.h
(listings and the per-entry headers go to <repo>/out/tone-mapping/shaders). Needs VAMKIT_FXC (the Windows SDK bin
folder for x64, or fxc.exe in it)."""
import os
import subprocess
from pathlib import Path

REPO = next(p for p in Path(__file__).resolve().parents if (p / "components").is_dir())
COMP = Path(__file__).resolve().parent.parent

ENTRIES = [("CSDownFirst", "kTmDownFirst"), ("CSDown", "kTmDown"), ("CSUp", "kTmUp"), ("CSComposite", "kTmComposite"),
           ("CSCompositeFilm", "kTmCompositeFilm"), ("CSCompositeInPlace", "kTmCompositeInPlace"),
           ("CSCompositeFilmInPlace", "kTmCompositeFilmInPlace")]


def find_fxc():
    v = os.environ.get("VAMKIT_FXC")
    if not v:
        raise SystemExit("set VAMKIT_FXC to the Windows SDK bin folder for x64 (the one holding fxc.exe)")
    f = v if v.lower().endswith(".exe") else os.path.join(v, "fxc.exe")
    if not os.path.isfile(f):
        raise SystemExit("VAMKIT_FXC=%s: no fxc.exe there" % v)
    return f


def main():
    src = str(COMP / "shaders" / "tonemap.hlsl")
    tmp = str(REPO / "out" / "tone-mapping" / "shaders")
    gen = REPO / "out" / "gen" / "tone-mapping"
    os.makedirs(tmp, exist_ok=True)
    gen.mkdir(parents=True, exist_ok=True)
    fxc = find_fxc()
    parts = ["// Generated by tools/build_shaders.py from shaders/tonemap.hlsl; do not edit.\n#pragma once\n"]
    sizes = []
    for entry, name in ENTRIES:
        header = os.path.join(tmp, entry + ".h")
        cmd = [fxc, "/nologo", "/O3", "/T", "cs_5_0", "/E", entry, "/Vn", name, "/Fh", header,
               "/Fc", os.path.join(tmp, entry + ".asm"), src]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit("fxc %s failed:\n%s%s" % (entry, r.stdout, r.stderr))
        with open(header, "r", encoding="ascii", errors="replace") as f:
            parts.append(f.read().replace("const BYTE", "static const unsigned char"))
        sizes.append("%s %d B" % (entry, os.path.getsize(header)))
    out = str(gen / "tm_shaders.h")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(parts))
    print("tm_shaders.h: " + ", ".join(sizes))


if __name__ == "__main__":
    main()
