"""Generates the export side of the test proxy d3d11.dll from the real one's export table:

    d3d11_thunks.asm   one `jmp [p_<name>]` thunk per export the proxy does not implement itself
    d3d11.def          every export, same names and ordinals; ours map to Proxy_<name>, the rest to t_<name>
    d3d11_thunks.inc   the names, for d3d11_proxy.cpp to fill p_<name> from the real DLL

    python -I -B gen_thunks.py <real d3d11.dll> <out dir>
"""
import struct
import sys
from pathlib import Path

OWN = {'D3D11CreateDevice'}  # implemented in d3d11_proxy.cpp


def exports(path):
    d = Path(path).read_bytes()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    assert d[pe:pe + 4] == b'PE\0\0'
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    opt = pe + 24
    assert struct.unpack_from('<H', d, opt)[0] == 0x20b, 'not PE32+'
    exp_rva = struct.unpack_from('<I', d, opt + 112)[0]
    sec = opt + struct.unpack_from('<H', d, pe + 20)[0]
    sections = [struct.unpack_from('<8sIIII', d, sec + 40 * i) for i in range(nsec)]

    def off(rva):
        for _, vsize, va, rsize, raw in sections:
            if va <= rva < va + max(vsize, rsize):
                return rva - va + raw
        raise ValueError(hex(rva))
    e = off(exp_rva)
    base, nfun, nname, afun, aname, aord = struct.unpack_from('<IIIIII', d, e + 16)
    out = []
    for i in range(nname):
        nrva = struct.unpack_from('<I', d, off(aname) + 4 * i)[0]
        o = off(nrva)
        name = d[o:d.index(b'\0', o)].decode()
        ordinal = struct.unpack_from('<H', d, off(aord) + 2 * i)[0] + base
        out.append((name, ordinal))
    assert len(out) == nfun, 'unnamed exports: %d functions, %d names' % (nfun, nname)
    return sorted(out, key=lambda x: x[1])


def main():
    real, outdir = sys.argv[1], Path(sys.argv[2])
    ex = exports(real)
    forwarded = [(n, o) for n, o in ex if n not in OWN]
    asm = ['; generated by gen_thunks.py from %s' % real, '.data']
    asm += ['PUBLIC p_%s\np_%s DQ 0' % (n, n) for n, _ in forwarded]
    asm += ['.code']
    asm += ['PUBLIC t_%s\nt_%s PROC\n    jmp QWORD PTR [p_%s]\nt_%s ENDP' % (n, n, n, n) for n, _ in forwarded]
    asm += ['END']
    (outdir / 'd3d11_thunks.asm').write_text('\n'.join(asm) + '\n', encoding='ascii')
    de = ['LIBRARY d3d11', 'EXPORTS']
    de += ['    %s=%s_%s @%d' % (n, 'Proxy' if n in OWN else 't', n, o) for n, o in ex]
    (outdir / 'd3d11.def').write_text('\n'.join(de) + '\n', encoding='ascii')
    inc = ['// generated by gen_thunks.py: X(name) for every export forwarded to the real d3d11.dll']
    inc += ['X(%s)' % n for n, _ in forwarded]
    (outdir / 'd3d11_thunks.inc').write_text('\n'.join(inc) + '\n', encoding='ascii')
    print('%d exports, %d forwarded, own: %s' % (len(ex), len(forwarded), ', '.join(sorted(OWN))))


if __name__ == '__main__':
    main()
