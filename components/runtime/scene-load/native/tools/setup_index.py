"""vorbis_setups.exe's output (records {u32 crc; i32 channels; i32 rate; f32 q; u32 size; data}) -> native\\vorbis_setup_index.h.
    python -I setup_index.py <setups.bin>"""
import os, struct, sys

b = open(sys.argv[1], 'rb').read()
q, rows = 0, []
while q < len(b):
    crc, ch, rate, qq, sz = struct.unpack('<IiifI', b[q:q + 20])
    qb = struct.unpack('<I', b[q + 12:q + 16])[0]
    q += 20 + sz
    rows.append((crc, ch, rate, qb, qq, sz))
rows.sort()
out = ["// Vorbis setup headers that libvorbis 1.3.7's encoder makes (vorbis_encode_init_vbr), by CRC32 of the setup packet",
       "// (= how FMOD's FSB5 names the setup a clip was encoded with). Generated by native\\tools\\vorbis_setups.exe",
       "// (channels 1-8, 12 rates, quality -0.1 .. 1.0 in steps of 0.001) and native\\tools\\setup_index.py; q is the float",
       "// passed to the encoder, as its bits. Regenerating one gives back the same bytes (checked by CRC when it is made).",
       'struct VorbisSetupIndex { unsigned crc; int channels; int rate; unsigned qbits; };',
       'static const VorbisSetupIndex kVorbisSetups[] = {']
for crc, ch, rate, qb, qq, sz in rows:
    out.append('    { 0x%08xu, %d, %d, 0x%08xu },   // q %.3f, %d bytes' % (crc, ch, rate, qb, qq, sz))
out.append('};')
dst = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'vorbis_setup_index.h')
open(dst, 'w').write('\n'.join(out) + '\n')
print(len(rows), 'setups ->', dst)
